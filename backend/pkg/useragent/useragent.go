// Package useragent 存放全应用出站 HTTP 请求统一使用的 User-Agent。
//
// 为什么单独占一个包：这个值原先在各个抓取/下载点被复制了 16 遍，而且其中
// 大多数是**截断版**（`...AppleWebKit/537.36"` 后面既没有 `(KHTML, like
// Gecko)` 也没有 Chrome 版本号）。平台 CDN 对截断 UA 更容易判成爬虫，症状
// 是「取链探活成功，但真正播放/下载时 403」。
//
// 放在一个**不依赖任何本项目包**的叶子包里，任何包都能引用它而不会引入
// 循环依赖。
package useragent

// Desktop 是一个桌面 Chrome 的 UA。
//
// 四家平台对非浏览器 UA 的响应差别很大（有的直接拒绝，有的返回降质结果），
// 所以全应用固定用这一个 —— 握手阶段与真正拉流/下载阶段必须是同一个值，
// 否则会出现「探活过、播放 403」这种只在第二阶段暴露的失败。
//
// 版本号沿用真机验证过的那一个，不随手升级：改它等于改所有平台的指纹，
// 要改就单独作为一次变更并重新上机验证。
const Desktop = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 " +
	"(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36"
