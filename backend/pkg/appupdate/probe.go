package appupdate

// 「已下载更新包」的磁盘探测。
//
// 用户 2026-11-02 的第 1 项要求：「增加『已下载更新包』探测：若已存在更新包
// 则直接复用，避免二次下载」。
//
// 为什么需要它：下载状态（m.dl）是**进程级内存状态**。曲率每次安装/升级、
// 或者用户手工重启应用，进程都会重开，内存里的 ready 就没了 —— 而
// <dataDir>/updates/ 下的 yinshu-ai-x.y.z.fpk 还躺在磁盘上。此时用户再点
// 「更新」，程序会从头再下一遍同样的几十 MB，白等一次、还可能再失败一次。
//
// 这里的实现刻意**不信任文件名以外的任何东西**：
//   - 版本号只从文件名解析（下载落盘时用的就是 release 里的资产名）；
//   - 只认比当前版本新的包（旧包装了等于没装）；
//   - 同名 .part 存在就跳过（上次没下完，本体不可信）；
//   - 包内的 manifest 校验留给安装脚本那一跳 —— 这里多读一遍 tar 只为
//     「省一次下载」，不值得让状态查询变慢。
//
// 具体扫描逻辑在 manager.go 的 probeDownloadedLocked（需要持有 m.mu）。
